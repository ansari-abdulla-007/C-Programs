// Write a C program to demonstrate arithmetic operators.
#include <stdio.h>
int main(){
    int a=10, b=20;
    
    printf("addition: %d\n",a+b);
    printf("substraction: %d\n",a-b);
    printf("multiplication: %d\n",a*b);
    printf("division: %d\n",a/b);
    printf("modulus: %d\n",a%b);

    return 0;
}